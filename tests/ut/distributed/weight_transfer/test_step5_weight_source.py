import json

import pytest
import torch
from safetensors.torch import save_file

from tests.step5_weight_source import Step5CheckpointSource


@pytest.mark.parametrize("sharded", [False, True])
def test_step5_weight_source_contract(tmp_path, sharded):
    expected = {
        "model.embed_tokens.weight": torch.arange(12).reshape(3, 4).to(torch.bfloat16),
        "model.layers.3.moe.router_bias": torch.tensor([0.125, -0.25], dtype=torch.float32),
    }
    if sharded:
        mapping = {}
        for i, (name, value) in enumerate(expected.items()):
            shard = f"model-{i}.safetensors"
            save_file({name: value}, str(tmp_path / shard))
            mapping[name] = shard
        (tmp_path / "model.safetensors.index.json").write_text(json.dumps({"weight_map": mapping}))
    else:
        save_file(expected, str(tmp_path / "model.safetensors"))
    source = Step5CheckpointSource(tmp_path)
    metadata = source.metadata()
    assert [m.name for m in metadata] == sorted(expected)
    for _ in range(2):
        values = list(source)
        assert len(values) == len(expected)
        for meta, (name, tensor) in zip(metadata, values, strict=True):
            assert name == meta.name
            assert tensor.dtype == meta.dtype == expected[name].dtype
            assert tuple(tensor.shape) == meta.shape == tuple(expected[name].shape)
            assert torch.equal(tensor, expected[name])


@pytest.mark.parametrize("prefix", ["model.", "language_model.model."])
def test_step5_checkpoint_parameter_mapping(tmp_path, prefix):
    # Independent checkpoint contract, not expectations generated by an adapter.
    expected = {
        prefix + "layers.3.moe.router_bias": torch.tensor([0.125, -0.25]),
        prefix + "layers.3.moe.gate.weight": torch.arange(8, dtype=torch.float32).reshape(2, 4),
        prefix + "layers.3.moe.share_expert.gate_proj.weight": torch.full((3, 4), 0.5, dtype=torch.bfloat16),
        prefix + "layers.3.moe.gate_proj.weight": torch.arange(24).reshape(2, 3, 4).to(torch.bfloat16),
        prefix + "layers.3.moe.up_proj.weight": torch.arange(24, 48).reshape(2, 3, 4).to(torch.bfloat16),
        prefix + "layers.3.moe.down_proj.weight": torch.arange(48, 72).reshape(2, 4, 3).to(torch.bfloat16),
    }
    save_file(expected, str(tmp_path / "model.safetensors"))
    actual = dict(Step5CheckpointSource(tmp_path))
    assert actual.keys() == expected.keys()
    for name in expected:
        assert actual[name].dtype == expected[name].dtype
        torch.testing.assert_close(actual[name], expected[name], rtol=0, atol=0)


def test_step5_weight_source_rejects_empty_checkpoint(tmp_path):
    save_file({}, str(tmp_path / "model.safetensors"))
    with pytest.raises(ValueError, match="Empty Step5 checkpoint"):
        Step5CheckpointSource(tmp_path)


def test_step5_weight_source_reports_missing_indexed_tensor(tmp_path):
    save_file({"present": torch.ones(1)}, str(tmp_path / "model.safetensors"))
    (tmp_path / "model.safetensors.index.json").write_text(json.dumps({"weight_map": {"missing": "model.safetensors"}}))
    source = Step5CheckpointSource(tmp_path)
    with pytest.raises(Exception, match="missing"):
        source.metadata()
    with pytest.raises(Exception, match="missing"):
        list(source)
