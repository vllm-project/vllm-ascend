"""JSONC loading (``//`` / ``/* */`` comments + trailing commas).

Extracted from config.py so both the hot-reload reader and external tooling
can parse the shipped ``.jsonc`` template the same way.
"""

from __future__ import annotations

import json
from typing import Any


def _strip_jsonc_comments(text: str) -> str:
    """String-aware removal of ``//`` line and ``/* */`` block comments."""
    out: list[str] = []
    i, n = 0, len(text)
    in_str = False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            i += 2
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i < n and not (text[i] == "*" and i + 1 < n and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def _strip_jsonc_trailing_commas(text: str) -> str:
    """String-aware removal of commas directly preceding ``}`` / ``]``."""
    out: list[str] = []
    i, n = 0, len(text)
    in_str = False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 1
            elif c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
            continue
        if c == ",":
            j = i + 1
            while j < n and text[j] in " \t\r\n":
                j += 1
            if j < n and text[j] in "}]":
                i += 1
                continue
        out.append(c)
        i += 1
    return "".join(out)


def loads_jsonc(text: str) -> Any:
    """``json.loads`` that also accepts ``//`` / ``/* */`` comments and trailing commas.

    Keeps the shipped ``.jsonc`` example template loadable as-is.
    """
    return json.loads(_strip_jsonc_trailing_commas(_strip_jsonc_comments(text)))
